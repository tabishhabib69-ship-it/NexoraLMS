import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

import '../../../data/dummy_data.dart';
import '../../../services/academic_service.dart';
import '../../../services/session_service.dart';
import '../../../services/study_assistant.dart';
import '../../../widgets/uni_widgets.dart';

class _Msg {
  final bool fromUser;
  final String text;
  final List<String> followUps;

  _Msg(this.fromUser, this.text, [this.followUps = const []]);
}

/// Uni-AI study companion (PDF page 8). Dark by design in both themes.
///
/// Talks to [StudyAssistant]; this build ships [DemoStudyAssistant], an
/// offline engine — the UI always says so.
class UniAiScreen extends StatefulWidget {
  final String? courseId;
  final String? initialPrompt;

  const UniAiScreen({super.key, this.courseId, this.initialPrompt});

  /// Conversation kept for the app session.
  static final List<_Msg> _history = [];
  static final StudyAssistant assistant = DemoStudyAssistant();

  @override
  State<UniAiScreen> createState() => _UniAiScreenState();
}

class _UniAiScreenState extends State<UniAiScreen> {
  final _input = TextEditingController();
  final _scroll = ScrollController();
  late String? _courseId = widget.courseId;
  bool _typing = false;
  final Set<int> _expanded = {};

  static const _bg = LinearGradient(
    begin: Alignment.topCenter,
    end: Alignment.bottomCenter,
    colors: [Color(0xFF222022), Color(0xFF2A2228), Color(0xFF3A2430)],
  );
  static const _glass = Color(0x1FFFFFFF);
  static const _glassBorder = Color(0x33FFFFFF);
  static const _muted = Color(0xFFB9AFA9);
  static const _sand = Color(0xFFCFC39E);

  static const _prompts = [
    'Explain Recursion',
    'Summarize Lecture',
    'Create MCQs',
    'Make Study Plan',
    'Flashcards',
    'Quiz Me',
  ];

  @override
  void initState() {
    super.initState();
    final p = widget.initialPrompt;
    if (p != null) WidgetsBinding.instance.addPostFrameCallback((_) => _send(p));
  }

  @override
  void dispose() {
    _input.dispose();
    _scroll.dispose();
    super.dispose();
  }

  Future<void> _send(String text) async {
    final prompt = text.trim();
    if (prompt.isEmpty || _typing) return;
    _input.clear();
    setState(() {
      UniAiScreen._history.add(_Msg(true, prompt));
      _typing = true;
    });
    _toBottom();
    final reply = await UniAiScreen.assistant.reply(prompt == 'Quiz Me' ? 'create mcqs' : prompt, courseId: _courseId);
    if (!mounted) return;
    setState(() {
      _typing = false;
      UniAiScreen._history.add(_Msg(false, reply, UniAiScreen.assistant.followUps(prompt)));
    });
    _toBottom();
  }

  void _toBottom() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_scroll.hasClients) {
        _scroll.animateTo(
          _scroll.position.maxScrollExtent,
          duration: Duration(milliseconds: 300),
          curve: Curves.easeOut,
        );
      }
    });
  }

  void _about() {
    showDialog(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text('About Uni-AI'),
        content: Text(
          UniAiScreen.assistant.isLive
              ? 'Answers are generated by AI and may contain mistakes. Verify with your course material.'
              : 'This demo build uses a small offline response engine with a fixed set of topics. '
                    'Answers are not verified course material — always check with your notes and instructor.',
        ),
        actions: [TextButton(onPressed: () => Navigator.pop(ctx), child: Text('Got it'))],
      ),
    );
  }

  Future<void> _newChat() async {
    if (UniAiScreen._history.isEmpty) return;
    final ok = await confirmAction(
      context,
      title: 'Start a new chat?',
      message: 'This clears the current conversation.',
      confirmLabel: 'Clear',
    );
    if (ok && mounted) setState(UniAiScreen._history.clear);
  }

  void _pickCourse() async {
    final picked = await showModalBottomSheet<String?>(
      context: context,
      backgroundColor: Color(0xFF2A2228),
      showDragHandle: true,
      builder: (sheet) => SafeArea(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            ListTile(
              title: Text('No course (general)', style: TextStyle(color: Colors.white)),
              trailing: _courseId == null ? Icon(Icons.check_rounded, color: _sand) : null,
              onTap: () => Navigator.pop(sheet, ''),
            ),
            for (final c in AcademicService.studentCourses)
              ListTile(
                title: Text('${c.code} · ${c.title}', style: TextStyle(color: Colors.white)),
                subtitle: Text(
                  '${DummyData.materials.where((m) => m.courseId == c.id).length} materials',
                  style: TextStyle(color: _muted),
                ),
                trailing: _courseId == c.id ? Icon(Icons.check_rounded, color: _sand) : null,
                onTap: () => Navigator.pop(sheet, c.id),
              ),
          ],
        ),
      ),
    );
    if (picked != null) setState(() => _courseId = picked.isEmpty ? null : picked);
  }

  @override
  Widget build(BuildContext context) {
    final first = (SessionService.currentUser ?? DummyData.student).name.split(' ').first;
    final history = UniAiScreen._history;
    final course = _courseId == null ? null : DummyData.courseById(_courseId!);
    return Theme(
      data: ThemeData.dark(useMaterial3: true).copyWith(
        colorScheme: ColorScheme.dark(primary: _sand, surface: Color(0xFF2A2228)),
        dialogTheme: DialogThemeData(backgroundColor: Color(0xFF2E2729)),
      ),
      child: Scaffold(
        backgroundColor: Color(0xFF222022),
        body: Container(
          decoration: BoxDecoration(gradient: _bg),
          child: SafeArea(
            child: Column(
              children: [
                Padding(
                  padding: EdgeInsets.fromLTRB(16, 12, 16, 0),
                  child: Row(
                    children: [
                      CircleBackButton(onDark: true),
                      SizedBox(width: 12),
                      Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text(
                              'Powered by Uni-AI',
                              style: TextStyle(color: _sand, fontWeight: FontWeight.w700, fontSize: 13.5),
                            ),
                            Text(
                              'Study Companion',
                              style: TextStyle(color: Colors.white, fontSize: 24, fontWeight: FontWeight.w800),
                            ),
                          ],
                        ),
                      ),
                      IconButton(
                        tooltip: 'New chat',
                        onPressed: _newChat,
                        icon: Icon(Icons.add_comment_outlined, color: Colors.white),
                      ),
                      IconButton(
                        tooltip: 'About Uni-AI',
                        onPressed: _about,
                        icon: Icon(Icons.info_outline_rounded, color: Colors.white),
                      ),
                    ],
                  ),
                ),
                Expanded(
                  child: ListView(
                    controller: _scroll,
                    padding: EdgeInsets.fromLTRB(16, 14, 16, 16),
                    children: [
                      if (!UniAiScreen.assistant.isLive)
                        Container(
                          padding: EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                          decoration: BoxDecoration(color: Color(0x33E0962A), borderRadius: BorderRadius.circular(12)),
                          child: Text(
                            'Demo engine · answers are sample content, not verified course material',
                            textAlign: TextAlign.center,
                            style: TextStyle(color: Color(0xFFF2C98A), fontSize: 12),
                          ),
                        ),
                      SizedBox(height: 16),
                      Center(
                        child: Container(
                          width: 92,
                          height: 92,
                          decoration: BoxDecoration(
                            gradient: LinearGradient(colors: [Color(0xFF5A3A40), Color(0xFF9A5560)]),
                            borderRadius: BorderRadius.circular(30),
                            border: Border.all(color: _glassBorder),
                            boxShadow: [BoxShadow(color: Color(0x40000000), blurRadius: 24, offset: Offset(0, 10))],
                          ),
                          child: Icon(Icons.smart_toy_rounded, color: Colors.white, size: 46),
                        ),
                      ),
                      SizedBox(height: 14),
                      Text(
                        'Hello, $first! What can I help with?',
                        textAlign: TextAlign.center,
                        style: TextStyle(color: Colors.white, fontSize: 18, fontWeight: FontWeight.w700),
                      ),
                      SizedBox(height: 14),
                      Center(
                        child: ActionChip(
                          onPressed: _pickCourse,
                          avatar: Icon(Icons.menu_book_rounded, size: 18, color: _sand),
                          label: Text(
                            course == null ? 'Context: General' : 'Context: ${course.code}',
                            style: TextStyle(color: Colors.white, fontWeight: FontWeight.w700),
                          ),
                          backgroundColor: _glass,
                          side: BorderSide(color: _glassBorder),
                        ),
                      ),
                      SizedBox(height: 16),
                      Text(
                        'QUICK PROMPTS',
                        style: TextStyle(color: _sand, fontWeight: FontWeight.w800, letterSpacing: 1, fontSize: 12.5),
                      ),
                      SizedBox(height: 10),
                      Wrap(
                        spacing: 8,
                        runSpacing: 8,
                        children: [
                          for (final p in _prompts)
                            ActionChip(
                              onPressed: () => _send(p),
                              label: Text(
                                p,
                                style: TextStyle(color: Colors.white, fontWeight: FontWeight.w700),
                              ),
                              backgroundColor: _glass,
                              side: BorderSide(color: _glassBorder),
                              shape: StadiumBorder(),
                            ),
                        ],
                      ),
                      SizedBox(height: 18),
                      for (var i = 0; i < history.length; i++)
                        history[i].fromUser ? _userBubble(history[i].text) : _botBubble(i, history[i]),
                      if (_typing) _typingRow(),
                    ],
                  ),
                ),
                _composer(),
              ],
            ),
          ),
        ),
      ),
    );
  }

  Widget _userBubble(String text) {
    return Align(
      alignment: Alignment.centerRight,
      child: Container(
        margin: EdgeInsets.only(left: 56, bottom: 14),
        padding: EdgeInsets.symmetric(horizontal: 18, vertical: 14),
        decoration: BoxDecoration(
          gradient: LinearGradient(colors: [Color(0xFF5A3A40), Color(0xFF8C4A53)]),
          borderRadius: BorderRadius.only(
            topLeft: Radius.circular(24),
            topRight: Radius.circular(24),
            bottomLeft: Radius.circular(24),
            bottomRight: Radius.circular(6),
          ),
        ),
        child: Text(text, style: TextStyle(color: Colors.white, fontSize: 15.5, height: 1.4)),
      ),
    );
  }

  Widget _botBubble(int index, _Msg m) {
    final lines = m.text.split('\n');
    final long = lines.length > 8 && !_expanded.contains(index);
    final shown = long ? lines.take(7).toList() : lines;
    return Padding(
      padding: EdgeInsets.only(bottom: 14),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Container(
            width: 38,
            height: 38,
            decoration: BoxDecoration(
              gradient: LinearGradient(colors: [Color(0xFF5A3A40), Color(0xFF9A5560)]),
              borderRadius: BorderRadius.circular(12),
            ),
            child: Icon(Icons.smart_toy_rounded, size: 20, color: Colors.white),
          ),
          SizedBox(width: 10),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Container(
                  width: double.infinity,
                  padding: EdgeInsets.fromLTRB(18, 14, 18, 12),
                  decoration: BoxDecoration(
                    color: _glass,
                    borderRadius: BorderRadius.circular(22),
                    border: Border.all(color: _glassBorder),
                  ),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      ..._renderMarkup(shown),
                      if (long)
                        GestureDetector(
                          onTap: () => setState(() => _expanded.add(index)),
                          child: Padding(
                            padding: EdgeInsets.only(top: 6),
                            child: Text(
                              'Tap to expand full answer',
                              style: TextStyle(color: _sand, fontWeight: FontWeight.w700),
                            ),
                          ),
                        ),
                      Align(
                        alignment: Alignment.centerRight,
                        child: TextButton.icon(
                          onPressed: () {
                            Clipboard.setData(ClipboardData(text: m.text.replaceAll('## ', '')));
                            showSnack(context, 'Answer copied');
                          },
                          icon: Icon(Icons.copy_rounded, size: 16, color: _muted),
                          label: Text('Copy', style: TextStyle(color: _muted)),
                        ),
                      ),
                    ],
                  ),
                ),
                if (m.followUps.isNotEmpty && index == UniAiScreen._history.length - 1) ...[
                  SizedBox(height: 10),
                  Wrap(
                    spacing: 8,
                    runSpacing: 8,
                    children: [
                      for (final f in m.followUps)
                        ActionChip(
                          onPressed: () => _send(f),
                          avatar: Icon(Icons.subdirectory_arrow_right_rounded, size: 16, color: _sand),
                          label: Text(f, style: TextStyle(color: Colors.white, fontSize: 13)),
                          backgroundColor: Colors.transparent,
                          side: BorderSide(color: _glassBorder),
                          shape: StadiumBorder(),
                        ),
                    ],
                  ),
                ],
              ],
            ),
          ),
        ],
      ),
    );
  }

  /// Renders the assistant's lightweight markup (headings, bullets, Q/A cards).
  List<Widget> _renderMarkup(List<String> lines) {
    final out = <Widget>[];
    for (var i = 0; i < lines.length; i++) {
      final l = lines[i];
      if (l.startsWith('## ')) {
        out.add(
          Padding(
            padding: EdgeInsets.only(top: out.isEmpty ? 0 : 10, bottom: 4),
            child: Text(
              l.substring(3),
              style: TextStyle(color: Colors.white, fontSize: 16.5, fontWeight: FontWeight.w800),
            ),
          ),
        );
      } else if (l.startsWith('- ')) {
        out.add(
          Padding(
            padding: EdgeInsets.only(bottom: 4),
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Padding(
                  padding: EdgeInsets.only(top: 7),
                  child: Icon(Icons.circle, size: 6, color: _sand),
                ),
                SizedBox(width: 8),
                Expanded(
                  child: Text(l.substring(2), style: TextStyle(color: Color(0xFFEDE6E6), fontSize: 14.5, height: 1.45)),
                ),
              ],
            ),
          ),
        );
      } else if (l.startsWith('Q: ')) {
        final answer = i + 1 < lines.length && lines[i + 1].startsWith('A: ') ? lines[i + 1].substring(3) : '';
        if (answer.isNotEmpty) i++;
        out.add(_QaCard(question: l.substring(3), answer: answer));
      } else if (l.trim().isNotEmpty) {
        out.add(
          Padding(
            padding: EdgeInsets.only(bottom: 4),
            child: Text(l, style: TextStyle(color: Color(0xFFEDE6E6), fontSize: 15, height: 1.5)),
          ),
        );
      }
    }
    return out;
  }

  Widget _typingRow() {
    return Row(
      children: [
        Container(
          padding: EdgeInsets.symmetric(horizontal: 14, vertical: 12),
          decoration: BoxDecoration(color: _glass, borderRadius: BorderRadius.circular(16)),
          child: Row(
            mainAxisSize: MainAxisSize.min,
            children: [
              for (var i = 0; i < 3; i++)
                Container(
                  margin: EdgeInsets.symmetric(horizontal: 2),
                  width: 7,
                  height: 7,
                  decoration: BoxDecoration(color: _muted, shape: BoxShape.circle),
                ),
            ],
          ),
        ),
        SizedBox(width: 10),
        Text('Uni-AI is typing…', style: TextStyle(color: _muted, fontSize: 13)),
      ],
    );
  }

  Widget _composer() {
    return Padding(
      padding: EdgeInsets.fromLTRB(14, 6, 14, 14),
      child: Container(
        padding: EdgeInsets.all(8),
        decoration: BoxDecoration(
          color: Color(0x2EFFFFFF),
          borderRadius: BorderRadius.circular(28),
          border: Border.all(color: _glassBorder),
        ),
        child: Row(
          children: [
            _RoundIcon(icon: Icons.attach_file_rounded, tooltip: 'Use course materials', onTap: _pickCourse),
            SizedBox(width: 8),
            Expanded(
              child: TextField(
                controller: _input,
                style: TextStyle(color: Colors.white),
                minLines: 1,
                maxLines: 4,
                textInputAction: TextInputAction.send,
                onSubmitted: _send,
                decoration: InputDecoration(
                  hintText: 'Ask anything about your studies…',
                  hintStyle: TextStyle(color: _muted),
                  border: InputBorder.none,
                  enabledBorder: InputBorder.none,
                  focusedBorder: InputBorder.none,
                  filled: false,
                  isDense: true,
                ),
              ),
            ),
            _RoundIcon(
              icon: Icons.mic_none_rounded,
              tooltip: 'Voice input',
              onTap: () => showSnack(context, 'Voice input is not available in the demo build.'),
            ),
            SizedBox(width: 8),
            _RoundIcon(icon: Icons.send_rounded, tooltip: 'Send', filled: true, onTap: () => _send(_input.text)),
          ],
        ),
      ),
    );
  }
}

class _RoundIcon extends StatelessWidget {
  final IconData icon;
  final String tooltip;
  final VoidCallback onTap;
  final bool filled;

  const _RoundIcon({required this.icon, required this.tooltip, required this.onTap, this.filled = false});

  @override
  Widget build(BuildContext context) {
    return Tooltip(
      message: tooltip,
      child: Material(
        color: Colors.transparent,
        child: InkWell(
          borderRadius: BorderRadius.circular(16),
          onTap: onTap,
          child: Ink(
            width: 46,
            height: 46,
            decoration: BoxDecoration(
              gradient: filled ? LinearGradient(colors: [Color(0xFF2E2729), Color(0xFF8C4A53)]) : null,
              color: filled ? null : Color(0x1FFFFFFF),
              borderRadius: BorderRadius.circular(16),
            ),
            child: Icon(icon, color: Colors.white, size: 22),
          ),
        ),
      ),
    );
  }
}

class _QaCard extends StatefulWidget {
  final String question;
  final String answer;

  const _QaCard({required this.question, required this.answer});

  @override
  State<_QaCard> createState() => _QaCardState();
}

class _QaCardState extends State<_QaCard> {
  bool _open = false;

  @override
  Widget build(BuildContext context) {
    return GestureDetector(
      onTap: () => setState(() => _open = !_open),
      child: AnimatedContainer(
        duration: Duration(milliseconds: 200),
        width: double.infinity,
        margin: EdgeInsets.only(bottom: 8, top: 4),
        padding: EdgeInsets.all(14),
        decoration: BoxDecoration(
          color: _open ? Color(0x334E9B78) : Color(0x14FFFFFF),
          borderRadius: BorderRadius.circular(16),
          border: Border.all(color: Color(0x33FFFFFF)),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              widget.question,
              style: TextStyle(color: Colors.white, fontWeight: FontWeight.w700, fontSize: 14.5),
            ),
            SizedBox(height: 6),
            Text(
              _open ? widget.answer : 'Tap to reveal answer',
              style: TextStyle(color: _open ? Color(0xFFBDF0E2) : Color(0xFFB9AFA9), fontSize: 14),
            ),
          ],
        ),
      ),
    );
  }
}
